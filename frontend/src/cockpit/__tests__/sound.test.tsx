 it('uses monotonic receive time, source identity and precise quiet/clipping/stale thresholds',()=>{
  let now=0;const store=new MeterStore(()=>now);store.setConnected(true)
  const send=(rms:number,peak:number,name='monitor-a')=>store.accept({streamKind:'system',sourceName:name,level:.8,rms,peak,t:999999})
  expect(store.read('system',null).state).toBe('unavailable');expect(store.read('system','monitor-a').state).toBe('stale')
  send(.0009,.0049);expect(store.read('system','monitor-a').state).toBe('quiet')
  send(.001,.0049);expect(store.read('system','monitor-a').state).toBe('active')
  send(.1,.98);expect(store.read('system','monitor-a').state).toBe('clipping')
  now=499;send(.0001,.001);expect(store.read('system','monitor-a').state).toBe('clipping')
  now=500;expect(store.read('system','monitor-a').state).toBe('quiet')
  expect(store.read('system','monitor-b').state).toBe('stale')
  now=2499;expect(store.read('system','monitor-a').state).toBe('stale')
  store.fail('system','Old device failure','monitor-b');expect(store.read('system','monitor-a').state).toBe('stale')
  store.fail('system','Fixture failure');expect(store.read('system','monitor-a').state).toBe('unavailable')
  store.setConnected(false);expect(store.read('system','monitor-a').state).toBe('disconnected')
  store.setConnected(true);expect(store.read('system','monitor-a').state).toBe('stale')
 })
